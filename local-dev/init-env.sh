#!/usr/bin/env bash
# Creates local-dev/.env with random local-only secrets, or adds keys missing from an existing .env. Existing values
# are never changed: the PostgreSQL volume keeps the passwords it was created with (see README for an old volume).
set -euo pipefail
cd "$(dirname "$0")"
rand() { openssl rand -base64 48 | tr -dc 'A-Za-z0-9' | head -c "${1:-40}"; }
hex() { openssl rand -hex 16; }
umask 077
[[ -e .env ]] || printf '# Local-only values generated by init-env.sh. Not for any shared or production environment. Do not commit.\n' > .env
added=0
put() {
  if ! grep -q "^$1=" .env; then
    printf '%s=%s\n' "$1" "$2" >> .env
    added=$((added + 1))
  fi
}
put LOCAL_TENANT_ID 00000000-0000-4000-8000-000000000001
put LOCAL_TENANT_KEY local
put LOCAL_TENANT_NAME Local
put LOCAL_ADMIN_USERNAME admin
put LOCAL_ADMIN_PASSWORD "$(rand 20)"
put LOCAL_POSTGRES_PORT 15432
put POSTGRES_SUPERUSER_PASSWORD "$(rand)"
put IDENTITY_DB_PASSWORD "$(rand)"
put ERP_DB_PASSWORD "$(rand)"
put WORKFLOW_DB_PASSWORD "$(rand)"
put WORKFLOW_OWNER_DB_PASSWORD "$(rand)"
put WORKFLOW_SCHEDULER_DB_PASSWORD "$(rand)"
put WORKFLOW_PROJECTOR_DB_PASSWORD "$(rand)"
put WORKFLOW_ARCHIVER_DB_PASSWORD "$(rand)"
put REDIS_PASSWORD "$(rand)"
put IDENTITY_KEY_ENCRYPTION_PASSWORD "$(rand 48)"
put IDENTITY_KEY_ENCRYPTION_SALT "$(hex)"
put IDENTITY_SERVICE_CLIENT_SECRET "$(rand 48)"
put ERP_BFF_CLIENT_SECRET "$(rand 48)"
put ERP_SERVICE_CLIENT_SECRET "$(rand 48)"
put ERP_SESSION_ENCRYPTION_PASSWORD "$(rand 48)"
put ERP_SESSION_ENCRYPTION_SALT "$(hex)"
echo "$(pwd)/.env: $added key(s) added; login: $(grep '^LOCAL_ADMIN_USERNAME=' .env | cut -d= -f2) / see LOCAL_ADMIN_PASSWORD"
